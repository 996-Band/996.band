import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const repoRoot = process.cwd();
const distRoot = path.join(repoRoot, 'dist');
const imageExtensions = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.svg', '.webp']);
const cachePrefix = '996band-images-';
const runtimeLimit = 240;
const mediaManifest = JSON.parse(
  await readFile(path.join(repoRoot, 'src/data/media-assets.json'), 'utf8'),
);
const configuredAssetBaseUrl = String(process.env.PUBLIC_ASSET_BASE_URL || '').trim().replace(/\/+$/g, '');
const trustedRemoteOrigins = configuredAssetBaseUrl
  ? [new URL(configuredAssetBaseUrl).origin]
  : [];

const walk = async (directory) => {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(target));
    if (entry.isFile()) files.push(target);
  }
  return files;
};

const toPublicUrl = (file) => `/${path.relative(distRoot, file).split(path.sep).join('/')}`;
const normalizeAssetUrl = (value) => {
  const pathname = value.split(/[?#]/, 1)[0];
  if (pathname.startsWith('/')) return pathname;
  try {
    const url = new URL(pathname);
    return ['http:', 'https:'].includes(url.protocol) ? url.toString() : null;
  } catch {
    return null;
  }
};
const isImageUrl = (value) => {
  try {
    return imageExtensions.has(path.extname(new URL(value, 'https://local.invalid').pathname).toLowerCase());
  } catch {
    return false;
  }
};

const allDistFiles = await walk(distRoot);
const imageFiles = allDistFiles
  .filter((file) => imageExtensions.has(path.extname(file).toLowerCase()))
  .sort();

if (!imageFiles.length) {
  throw new Error('No built image assets found. Run this script after astro build.');
}

const versionHash = createHash('sha256');
versionHash.update(mediaManifest.version);
versionHash.update(configuredAssetBaseUrl);
for (const file of imageFiles) {
  versionHash.update(toPublicUrl(file));
  versionHash.update(await readFile(file));
}
const version = versionHash.digest('hex').slice(0, 12);

const homepageHtml = await readFile(path.join(distRoot, 'index.html'), 'utf8');
const criticalUrls = new Set();
const htmlAssetPattern = /(?:src|href)=["']([^"']+)["']/g;
for (const match of homepageHtml.matchAll(htmlAssetPattern)) {
  const assetUrl = normalizeAssetUrl(match[1]);
  if (assetUrl && isImageUrl(assetUrl)) criticalUrls.add(assetUrl);
}

const cssFiles = allDistFiles.filter((file) => file.endsWith('.css'));
const cssAssetPattern = /url\(\s*["']?([^"')]+)["']?\s*\)/g;
for (const file of cssFiles) {
  const css = await readFile(file, 'utf8');
  for (const match of css.matchAll(cssAssetPattern)) {
    const assetUrl = normalizeAssetUrl(match[1]);
    if (assetUrl && isImageUrl(assetUrl)) criticalUrls.add(assetUrl);
  }
}

const imageFileUrls = new Set(imageFiles.map(toPublicUrl));
const verifiedCriticalUrls = [...criticalUrls]
  .filter((assetUrl) => {
    if (assetUrl.startsWith('/')) return imageFileUrls.has(decodeURIComponent(assetUrl));
    return trustedRemoteOrigins.includes(new URL(assetUrl).origin);
  })
  .sort();

const localHero = '/assets/design/homepage-hero-stage-clean.webp';
const remoteHeroEntry = mediaManifest.assets[localHero];
const expectedHero = configuredAssetBaseUrl && remoteHeroEntry
  ? `${configuredAssetBaseUrl}/${remoteHeroEntry.objectKey}`
  : localHero;
if (!verifiedCriticalUrls.includes(expectedHero)) {
  throw new Error('Homepage hero image is missing from the critical image cache manifest.');
}

const serviceWorker = `/* Generated by scripts/generate-image-service-worker.mjs. */
const CACHE_PREFIX = ${JSON.stringify(cachePrefix)};
const VERSION = ${JSON.stringify(version)};
const CRITICAL_CACHE = \`\${CACHE_PREFIX}critical-\${VERSION}\`;
const RUNTIME_CACHE = \`\${CACHE_PREFIX}runtime-\${VERSION}\`;
const RUNTIME_LIMIT = ${runtimeLimit};
const CRITICAL_IMAGES = ${JSON.stringify(verifiedCriticalUrls, null, 2)};
const CRITICAL_URLS = new Set(CRITICAL_IMAGES.map((value) => new URL(value, self.location.origin).href));
const TRUSTED_IMAGE_ORIGINS = new Set([self.location.origin, ...${JSON.stringify(trustedRemoteOrigins)}]);
const IMAGE_EXTENSIONS = /\\.(?:avif|gif|jpe?g|png|svg|webp)$/i;

const isCacheableResponse = (response) => response && (response.ok || response.type === 'opaque');

const trimCache = async (cacheName, limit) => {
  const cache = await caches.open(cacheName);
  const keys = await cache.keys();
  await Promise.all(keys.slice(0, Math.max(0, keys.length - limit)).map((request) => cache.delete(request)));
};

const updateCache = async (cacheName, request) => {
  const response = await fetch(request);
  if (isCacheableResponse(response)) {
    const cache = await caches.open(cacheName);
    await cache.put(request, response.clone());
    if (cacheName === RUNTIME_CACHE) await trimCache(cacheName, RUNTIME_LIMIT);
  }
  return response;
};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CRITICAL_CACHE);
    await Promise.allSettled(CRITICAL_IMAGES.map(async (value) => {
      const url = new URL(value, self.location.origin);
      const request = new Request(url.href, {
        mode: url.origin === self.location.origin ? 'same-origin' : 'no-cors',
        credentials: url.origin === self.location.origin ? 'same-origin' : 'omit',
      });
      const response = await fetch(request);
      if (isCacheableResponse(response)) await cache.put(request, response);
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const cacheNames = await caches.keys();
    await Promise.all(
      cacheNames
        .filter((cacheName) => cacheName.startsWith(CACHE_PREFIX) && ![CRITICAL_CACHE, RUNTIME_CACHE].includes(cacheName))
        .map((cacheName) => caches.delete(cacheName)),
    );
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (!TRUSTED_IMAGE_ORIGINS.has(url.origin)) return;
  if (request.destination !== 'image' && !IMAGE_EXTENSIONS.test(url.pathname)) return;

  event.respondWith((async () => {
    const cacheName = CRITICAL_URLS.has(url.href) ? CRITICAL_CACHE : RUNTIME_CACHE;
    const cache = await caches.open(cacheName);
    const cached = await cache.match(request);
    const revalidate = updateCache(cacheName, request).catch(() => cached);
    if (cached) {
      event.waitUntil(revalidate);
      return cached;
    }
    return revalidate;
  })());
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});
`;

const manifest = {
  version,
  cachePrefix,
  strategy: 'critical-precache + stale-while-revalidate',
  criticalImages: verifiedCriticalUrls,
  trustedImageOrigins: trustedRemoteOrigins,
  runtimeImageLimit: runtimeLimit,
  totalBuiltImages: imageFiles.length,
};

await mkdir(distRoot, { recursive: true });
await writeFile(path.join(distRoot, 'sw.js'), serviceWorker, 'utf8');
await writeFile(path.join(distRoot, 'image-cache-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

console.log(`Generated image service worker ${version}: ${verifiedCriticalUrls.length} critical / ${imageFiles.length} total images.`);
